_F = TypeVar("_F", bound=Callable[..., Any])


def repeat(job: Job, *args: Any, **kwargs: Any) -> Callable[[_F], _F]:
    """
    Decorator to schedule a new periodic job.

    Any additional arguments are passed on to the decorated function
    when the job runs.

    :param job: a :class:`Jobs <Job>`
    """

    def _schedule_decorator(decorated_function: _F) -> _F:
        job.do(decorated_function, *args, **kwargs)
        return decorated_function

    return _schedule_decorator


def _random_interval(earliest: float, latest: float) -> float:
    """
    Pick a random interval between `earliest` and `latest`, inclusive.

    Whole numbers (including floats such as 2.0) give a whole number, as
    random.randint() did before Python 3.12 stopped accepting floats. Other
    floats give any value in the range.
    """
    if float(earliest).is_integer() and float(latest).is_integer():
        # Randomized intervals only spread out load; they don't need to be
        # unpredictable, so the standard generator is fine.
        return random.randint(int(earliest), int(latest))  # noqa: S311
    return random.uniform(earliest, latest)  # noqa: S311


_UTC = datetime.timezone.utc

_WEEKDAYS = frozenset(range(5))
_WEEKEND = frozenset((5, 6))
_ALL_DAYS = frozenset(range(7))


def _parse_timezone(tz: str | datetime.tzinfo) -> datetime.tzinfo:
    if isinstance(tz, datetime.tzinfo):
        return tz
    if not isinstance(tz, str):
        raise ScheduleValueError("Timezone must be a string or a tzinfo object")
    try:
        import pytz
    except ModuleNotFoundError:
        pass
    else:
        # Prefer pytz when installed, for compatibility with schedule 1.2.
        return pytz.timezone(tz)

    import zoneinfo

    try:
        return zoneinfo.ZoneInfo(tz)
    except (zoneinfo.ZoneInfoNotFoundError, ValueError) as e:
        raise ScheduleValueError(
            "Unknown timezone {!r}. On Windows, install the tzdata package "
            "for timezone names to work.".format(tz)
        ) from e


def _now_utc() -> datetime.datetime:
    return datetime.datetime.now(_UTC)


def _wall_clock(
    moment: datetime.datetime, tz: datetime.tzinfo | None
) -> datetime.datetime:
    """
    The naive wall-clock time of a UTC moment in `tz`, or in local time if
    `tz` is None.
    """
    return moment.astimezone(tz).replace(tzinfo=None)


def _localize(wall: datetime.datetime, tz: datetime.tzinfo | None) -> datetime.datetime:
    """
    The UTC moment at which the clock in `tz` shows the naive time `wall`.
    Local time is used if `tz` is None.

    A wall-clock time that happens twice, when clocks go back, resolves to its
    first occurrence. A wall-clock time that does not exist, when clocks go
    forward, is moved forward by the size of the gap: 02:30 becomes 03:30
    when clocks jump from 02:00 to 03:00.
    """
    if tz is None:
        return wall.replace(fold=0).astimezone(_UTC)
    if hasattr(tz, "localize"):
        # pytz timezones need localize() to pick the correct UTC offset.
        import pytz

        aware: datetime.datetime
        try:
            aware = tz.localize(wall, is_dst=None)
        except pytz.AmbiguousTimeError:
            aware = tz.localize(wall, is_dst=True)
        except pytz.NonExistentTimeError:
            aware = tz.localize(wall, is_dst=False)
        return aware.astimezone(_UTC)
    return wall.replace(tzinfo=tz, fold=0).astimezone(_UTC)


def _move_to_next_weekday(moment: datetime.datetime, weekday: str) -> datetime.datetime:
    """
    Move the given timestamp to the nearest given weekday. May be this week
    or next week. If the timestamp is already at the given weekday, it is not
    moved.
    """
    weekday_index = _weekday_index(weekday)

    days_ahead = weekday_index - moment.weekday()
    if days_ahead < 0:
        # Target day already happened this week, move to next week
        days_ahead += 7
    return moment + datetime.timedelta(days=days_ahead)


def _weekday_index(day: str) -> int:
    weekdays = (
        "monday",
        "tuesday",
        "wednesday",
        "thursday",
        "friday",
        "saturday",
        "sunday",
    )
    if day not in weekdays:
        raise ScheduleValueError(
            "Invalid start day (valid start days are {})".format(weekdays)
        )
    return weekdays.index(day)
